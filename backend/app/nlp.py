def extract_symptoms(text: str, selected: list[str] | None = None) -> list[str]:
    """Extract canonical symptom names from free text and chip selections."""
    lower = re.sub(r"[^a-z0-9\s]", " ", text.lower())
    found = set()
    for canonical, phrases in ALIASES.items():
        for phrase in phrases:
            safe = re.escape(phrase)
            # Match whole word/phrase boundaries
            if re.search(rf"(?<![a-z]){safe}(?![a-z])", lower):
                # Do not count simple negated symptoms ("no fever", "not coughing") as present.
                start = re.search(rf"(?<![a-z]){safe}(?![a-z])", lower).start()
                before = lower[max(0, start - 18):start]
                if re.search(r"\b(no|not|never|without|don't|do not|isn't|is not|nahi|nahin)\s+(?:have\s+|having\s+|feel(?:ing)?\s+)?$", before):
                    continue
                found.add(canonical)
                break
    for item in (selected or []):
        found.add(clean_name(item))
    return sorted(found)

